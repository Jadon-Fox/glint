#!/usr/bin/env bash
# attach/runtime_attach.sh — Project 7 runtime attach interface
# Modelled on llmve-sensors attach contract.
# Usage: runtime_attach.sh --phase PHASE --out-dir OUT --mode MODE --pin PIN
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
P7_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

usage() {
    cat <<EOF
Usage: $0 --phase PHASE --out-dir OUT --mode MODE --pin PIN

Options:
  --phase PHASE   Execution phase (e.g. train, eval, probe)
  --out-dir OUT   Directory where boards/ output is written
  --mode MODE     Project 7 mode: 1 (INT8), 2 (INT8+offload), 3 (fold), 4 (fold+compress), 5 (resolution)
  --pin PIN       Path to model pin directory or file
  -h, --help      Display this help message and exit 0

Exit codes:
  0: Success (attached and env written)
  2: Bad arguments, unknown flag, or mode outside 1..5
  4: HARD_BLOCK (missing pin, missing library, schema mismatch, ABI mismatch)
EOF
}

PHASE=""
OUT_DIR=""
MODE=""
PIN=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        -h|--help)
            usage
            exit 0
            ;;
        --phase)
            [[ $# -ge 2 ]] || { echo "ERROR: --phase requires an argument" >&2; exit 2; }
            PHASE="$2"
            shift 2
            ;;
        --out-dir)
            [[ $# -ge 2 ]] || { echo "ERROR: --out-dir requires an argument" >&2; exit 2; }
            OUT_DIR="$2"
            shift 2
            ;;
        --mode)
            [[ $# -ge 2 ]] || { echo "ERROR: --mode requires an argument" >&2; exit 2; }
            MODE="$2"
            shift 2
            ;;
        --pin)
            [[ $# -ge 2 ]] || { echo "ERROR: --pin requires an argument" >&2; exit 2; }
            PIN="$2"
            shift 2
            ;;
        *)
            echo "ERROR: unknown flag: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

# Required arguments check
if [[ -z "$PHASE" || -z "$OUT_DIR" || -z "$MODE" || -z "$PIN" ]]; then
    echo "ERROR: Missing required arguments" >&2
    usage >&2
    exit 2
fi

# Mode validity check: must be integer 1..5
if [[ ! "$MODE" =~ ^[1-5]$ ]]; then
    echo "ERROR: Mode must be an integer 1..5, got: $MODE" >&2
    exit 2
fi

# Hard checks: Pin existence
if [[ ! -e "$PIN" ]]; then
    echo "HARD_BLOCK: pin path does not exist: $PIN" >&2
    exit 4
fi

PIN_JSON=""
if [[ -d "$PIN" && -f "$PIN/pin.json" ]]; then
    PIN_JSON="$PIN/pin.json"
elif [[ -f "$PIN" && "$PIN" == *.json ]]; then
    PIN_JSON="$PIN"
elif [[ -d "$PIN" ]]; then
    echo "HARD_BLOCK: missing pin.json in pin directory: $PIN" >&2
    exit 4
fi

# Schema check for mode
if [[ -n "$PIN_JSON" ]]; then
    SCHEMA="$(jq -r '.schema // empty' "$PIN_JSON" 2>/dev/null || true)"
    case "$MODE" in
        1)
            if [[ "$SCHEMA" != "bf16_to_int8_pin_v1" && "$SCHEMA" != "nf4_to_int8_pin_v1" ]]; then
                echo "HARD_BLOCK: Mode 1 requires bf16_to_int8_pin_v1, got $SCHEMA" >&2
                exit 4
            fi
            ;;
        2)
            if [[ "$SCHEMA" != "bf16_to_int8_pin_v1" && "$SCHEMA" != "nf4_to_int8_pin_v1" ]]; then
                echo "HARD_BLOCK: Mode 2 requires bf16_to_int8_pin_v1, got $SCHEMA" >&2
                exit 4
            fi
            ;;
        3|4|5)
            if [[ "$SCHEMA" != "nested_nf8_pin_v1" && "$SCHEMA" != "glint_pin_v1" ]]; then
                echo "HARD_BLOCK: Mode $MODE requires nested_nf8_pin_v1 or glint_pin_v1, got $SCHEMA" >&2
                exit 4
            fi
            ;;
    esac
fi

# Kernel library check
LIB_PATH="$P7_ROOT/lib/libp7_kernels.so"
if [[ ! -f "$LIB_PATH" ]]; then
    echo "HARD_BLOCK: sm_86 kernel library missing: $LIB_PATH" >&2
    exit 4
fi

ABI_FILE="$P7_ROOT/attach/ABI_VERSION"
if [[ ! -f "$ABI_FILE" ]]; then
    echo "HARD_BLOCK: ABI_VERSION file missing: $ABI_FILE" >&2
    exit 4
fi
ABI_VERSION="$(tr -d '[:space:]' < "$ABI_FILE")"

# Check that the symbol answers in the library
if ! nm -D "$LIB_PATH" 2>/dev/null | grep -q "p7_abi_version"; then
    echo "HARD_BLOCK: symbol p7_abi_version not found in $LIB_PATH" >&2
    exit 4
fi

LIB_SHA256="$(sha256sum "$LIB_PATH" | awk '{print $1}')"
COMMIT_SHA="$(git -C "$P7_ROOT" rev-parse HEAD 2>/dev/null || echo "uncommitted")"

BOARDS_DIR="$OUT_DIR/boards"
mkdir -p "$BOARDS_DIR"

ENV_FILE="$BOARDS_DIR/p7_runtime_attach.env"
cat > "$ENV_FILE" <<EOF
# Generated by Project 7 runtime_attach.sh
export P7_ATTACHED=1
export P7_ROOT="$P7_ROOT"
export P7_MODE="$MODE"
export P7_PIN="$PIN"
export P7_ABI_VERSION="$ABI_VERSION"
export P7_LIB_PATH="$LIB_PATH"
export P7_LIB_SHA256="$LIB_SHA256"
export P7_COMMIT_SHA="$COMMIT_SHA"
EOF

STAMP_FILE="$BOARDS_DIR/p7_runtime_attach_v1.json"
cat > "$STAMP_FILE" <<EOF
{
  "schema": "p7_runtime_attach_v1",
  "status": "attached",
  "phase": "$PHASE",
  "mode": $MODE,
  "pin": "$PIN",
  "abi_version": "$ABI_VERSION",
  "lib_sha256": "$LIB_SHA256",
  "commit_sha": "$COMMIT_SHA",
  "p7_root": "$P7_ROOT"
}
EOF

echo "P7_RUNTIME_ATTACH_OK mode=$MODE abi=$ABI_VERSION env=$ENV_FILE"
exit 0
